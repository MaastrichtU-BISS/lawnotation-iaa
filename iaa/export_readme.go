package iaa

import (
	"fmt"
	"strings"
)

// reportReadme describes the report from the same table definitions that
// produce it, so the column list cannot drift from the files beside it.
func reportReadme(data TaskData, report Report, confidence ConfidenceRatingSummary, tables []table) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# Inter-annotator agreement report\n\n")
	w("Generated by the IAA tool from a LawNotation (https://app.lawnotation.org) task export.\n\n")

	w("| | |\n|---|---|\n")
	w("| Documents | %d |\n", len(data.Documents))
	w("| Annotators | %s |\n", strings.Join(data.Annotators, ", "))
	w("| Annotation level | %s |\n", report.Meta.AnnotationLevel)
	w("| Labels | %s |\n", strings.Join(data.Labels, ", "))
	if len(data.DocumentLabels) > 0 {
		w("| Document labels | %s |\n", strings.Join(data.DocumentLabels, ", "))
	}
	if confidence.Alpha.Valid {
		w("| Krippendorff's alpha on confidence ratings | %s |\n", num(confidence.Alpha))
	}
	w("\n")

	w("`report.pdf`, when present, is the three tabs of the results page — per-label agreement,\n")
	w("confidence and suggestions — as a document. It is added by the web export; a report\n")
	w("made with the command-line tool has only the tables below.\n\n")

	w("## Reading the numbers\n\n")
	w("- **alpha** is Krippendorff's alpha and **kappa** Cohen's kappa: chance-corrected agreement,\n")
	w("  where 1 is perfect and 0 is what chance alone would produce. For span labels they are\n")
	w("  computed word by word over every document, so two annotators leaving the same sentence\n")
	w("  alone counts as agreement — compare `marked_units` with `total_units` in `labels.csv` to\n")
	w("  see how much of the text anyone marked.\n")
	w("- **f1_strict** and **f1_lenient** compare the spans themselves, two annotators at a time.\n")
	w("  Strict gives a partial match no credit; lenient counts it as half a false positive and\n")
	w("  half a false negative.\n")
	w("- An empty cell means the value does not exist for that row, never zero.\n\n")

	w("## Files\n\n")
	for _, t := range tables {
		w("### `%s`\n\n%s %d rows.\n\n", t.file, t.doc, len(t.rows))
		for _, c := range t.columns {
			if c.doc == "" {
				w("- `%s`\n", c.name)
				continue
			}
			w("- `%s` — %s\n", c.name, c.doc)
		}
		w("\n")
	}
	return []byte(b.String())
}
